import { expect, test } from '@playwright/test'

test('PDF page entry, 300% zoom and reading position survive closing and reloading', async ({ page }) => {
  await page.goto('/e2e/pdf-reader-fixture.html')
  const input = page.getByRole('textbox', { name: 'PDF 页码' })
  await input.click()
  const style=await input.evaluate(element=>{const css=getComputedStyle(element);return {outline:css.outlineStyle,shadow:css.boxShadow,radius:css.borderRadius}})
  expect(style).toEqual({outline:'none',shadow:'none',radius:'0px'})
  const zoom = page.getByRole('combobox', { name: 'PDF 缩放' })
  const canvas = page.getByRole('img', { name: 'PDF 第 4 页' }).or(page.locator('canvas[aria-label="PDF 第 4 页"]'))
  await expect(input).toBeEnabled()
  await input.fill('4')
  await input.press('Enter')
  await zoom.selectOption('3')
  await expect(zoom).toHaveValue('3')
  await expect(canvas).toHaveAttribute('width', /1[78]\d\d/)
  const host = page.locator('.file-viewer')
  const sheet = page.locator('.pdf-viewer__page')
  await host.evaluate(element => { element.scrollTop = 420 })
  await sheet.evaluate(element => { element.scrollLeft = 160 })
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('pdf-reading:019c0000-0000-7000-8000-000000000901') ?? '{}')))
    .toMatchObject({ page: 4, scale: 3, scrollTop: 420, scrollLeft: 160 })
  await page.getByRole('button', { name: '关闭 PDF' }).click()
  await page.getByRole('button', { name: '打开 PDF' }).click()
  await expect(input).toHaveValue('4')
  await expect.poll(() => host.evaluate(element => element.scrollTop)).toBe(420)
  await expect.poll(() => sheet.evaluate(element => element.scrollLeft)).toBe(160)
  await page.reload()
  await expect(input).toHaveValue('4')
  await expect(zoom).toHaveValue('3')
  await expect.poll(() => host.evaluate(element => element.scrollTop)).toBe(420)
  await expect.poll(() => sheet.evaluate(element => element.scrollLeft)).toBe(160)
  await page.screenshot({ path: 'test-results/pdf-reading-restored.png' })
  await input.fill('99')
  await input.press('Enter')
  await expect(input).toHaveValue('8')
  await expect(page.getByRole('button', { name: '下一页' })).toBeDisabled()
})
