test('Ctrl-wheel zooms Markdown content without scaling title controls or changing view state', async ({ page }) => {
  await page.goto('/e2e/v114-preferences-fixture.html')
  const body = page.locator('.editor-document__body')
  const title = page.locator('.editor-document-heading h1')
  const titleBefore = await title.boundingBox()
  await body.hover()
  await page.keyboard.down('Control')
  await page.mouse.wheel(0, -120)
  await page.keyboard.up('Control')
  await expect.poll(() => body.evaluate(element => getComputedStyle(element).zoom)).toBe('1.1')
  expect((await title.boundingBox())!.height).toBe(titleBefore!.height)
  await page.getByRole('textbox', { name: 'Markdown source' }).click()
  await page.keyboard.press(documentEndShortcut)
  await page.keyboard.type('zoom edit')
  await expect(page.getByRole('textbox', { name: 'Markdown source' })).toContainText('zoom edit')
  await page.getByRole('button', { name: '分栏校对' }).click()
  await expect.poll(() => body.evaluate(element => getComputedStyle(element).zoom)).toBe('1.1')
  await page.getByRole('button', { name: '阅读视图' }).click()
  await expect(page.locator('.markdown-preview')).toBeVisible()
  await body.hover()
  await page.keyboard.down('Control'); await page.mouse.wheel(0, 120); await page.keyboard.up('Control')
  await expect.poll(() => body.evaluate(element => getComputedStyle(element).zoom)).toBe('1')
})

