import { expect, test } from '@playwright/test'
test('horizontal table dragging reuses its floating header and does not echo rounded positions',async({page})=>{
 await page.goto('/e2e/table-readiness-fixture.html?long')
 const viewport=page.locator('.cm-live-table-viewport'),rail=page.locator('.cm-live-table-scrollbar')
 await viewport.locator('table').evaluate(table=>{table.style.minWidth='1800px'})
 await page.locator('.cm-scroller').evaluate(element=>{element.scrollTop=350})
 const header=page.locator('.floating-table-header table')
 await expect(header).toBeVisible()
 await page.evaluate(()=>new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve()))))
 const original=await header.locator('th').first().elementHandle()
 for(const offset of [80.25,160.5,240.75,320]){
   const actual=await rail.evaluate((element,value)=>{element.scrollLeft=value;element.dispatchEvent(new Event('scroll'));return element.scrollLeft},offset)
   await expect.poll(()=>viewport.evaluate(element=>element.scrollLeft)).toBe(actual)
 }
 expect(await original!.evaluate(element=>element===document.querySelector('.floating-table-header th'))).toBe(true)
})
test('preview tables float a header while scrolling the full table with the document', async ({page}) => {
  await page.goto('/e2e/table-readiness-fixture.html?long&preview')
  const viewport = page.locator('.markdown-table-viewport')
  await page.locator('.markdown-preview').evaluate(element=>{element.scrollTop=350})
  await expect(page.locator('.floating-table-header')).toBeVisible()
  expect(await viewport.evaluate(element=>element.scrollHeight-element.clientHeight)).toBeLessThan(3)
})
for (const rich of [false, true]) test(`long ${rich?'document':'Markdown'} table keeps its header visible`, async ({ page }) => {
  await page.goto(`/e2e/table-readiness-fixture.html?long${rich?'&rich':''}`)
  const viewport = page.locator(rich?'.tableWrapper':'.cm-live-table-viewport')
  await expect(viewport.locator('th').first()).toBeVisible()
  const scroller=page.locator(rich?'.rich-document__surface':'.cm-scroller')
  await scroller.evaluate(element => { element.scrollTop = 350 })
  await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBeGreaterThan(300)
  await expect(page.locator('.floating-table-header')).toBeVisible()
  expect(await viewport.evaluate(element=>element.scrollHeight-element.clientHeight)).toBeLessThan(3)
  const floating=(await page.locator('.floating-table-header').boundingBox())!,bounds=(await scroller.boundingBox())!
  expect(Math.abs(floating.y-Math.max(bounds.y,30))).toBeLessThan(4)
  expect(await page.locator('.floating-table-header').evaluate(element=>element.getAttribute('aria-hidden'))).toBe('true')
  if (rich) {
    await viewport.locator('td').filter({hasText:'selectable cell 10-1'}).click()
    const tools = page.getByRole('toolbar', {name:'表格工具'})
    await expect(tools).toBeVisible()
    expect(await tools.evaluate(element=>getComputedStyle(element).position)).toBe('fixed')
    await tools.getByRole('button', {name:'行列操作',exact:true}).hover()
    await expect(tools.getByRole('button', {name:'在下方插入行'})).toBeVisible()
    await page.screenshot({path:'test-results/rich-table-floating.png'})
  }
})
test('document table size picker escapes the context menu clipping', async ({page}) => {
  await page.goto('/e2e/table-readiness-fixture.html?rich')
  await page.getByRole('textbox',{name:'文档正文'}).click({button:'right'})
  const trigger=page.getByRole('menuitem',{name:'表格',exact:true})
  const menu=await trigger.boundingBox()
  await trigger.click({position:{x:menu!.width-8,y:menu!.height/2}})
  const grid = page.getByRole('grid',{name:'选择表格行列'})
  await expect(grid).toBeVisible()
  expect(await grid.evaluate(element=>element.parentElement===document.body)).toBe(true)
  await page.mouse.click(100,100)
  await page.getByRole('textbox',{name:'文档正文'}).click({button:'right'})
  await expect(grid).toHaveCount(0)
  await page.getByRole('menuitem',{name:'表格',exact:true}).click()
  await grid.getByRole('gridcell',{name:'3 行 3 列'}).click()
  await expect(grid).toHaveCount(0)
})
