import {expect,test} from '@playwright/test'
test('indirect references toggle locally with a bold graph heading',async({page})=>{
 await page.goto('/e2e/related-graph-fixture.html')
 await page.getByRole('button',{name:'关联笔记',exact:true}).click()
 const toggle=page.getByRole('switch',{name:'间接引用'})
 await expect(toggle).toBeChecked()
 const graph=page.getByRole('region',{name:'关联图谱'})
 expect(Number(await graph.locator('header strong').evaluate(element=>getComputedStyle(element).fontWeight))).toBeGreaterThanOrEqual(600)
 await toggle.uncheck()
 await expect(page.getByRole('button',{name:'打开笔记：综合练习'})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'打开笔记：申论基础'})).toBeVisible()
 await toggle.focus();await page.keyboard.press('Space')
 await expect(page.getByRole('button',{name:'打开笔记：综合练习'})).toBeVisible()
})
test('document context menu remains above the related panel and its lower items stay clickable',async({page})=>{
 await page.goto('/e2e/related-graph-fixture.html?rich')
 await page.getByRole('button',{name:'关联笔记',exact:true}).click()
 const body=page.getByRole('textbox',{name:'文档正文'})
 await body.click({button:'right',position:{x:80,y:20}})
 const menu=page.getByRole('menu',{name:'正文快捷操作'})
 await expect(menu).toBeVisible()
 const panel=await page.getByRole('region',{name:'关联笔记内容'}).boundingBox()
 const item=menu.getByRole('menuitem',{name:'清除格式',exact:true})
 const bounds=await item.boundingBox()
 expect(bounds!.y+bounds!.height).toBeGreaterThan(panel!.y)
 expect(await item.evaluate(element=>{const r=element.getBoundingClientRect();return element.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2))})).toBe(true)
 await page.screenshot({path:'test-results/related-menu-layers.png'})
 await item.click()
 await expect(menu).toHaveCount(0)
})
