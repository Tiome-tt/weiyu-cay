test('list and graph divider supports dragging, bounds, keyboard and reset',async({page})=>{
 await page.goto('/e2e/related-graph-fixture.html')
 await page.getByRole('button',{name:'关联笔记',exact:true}).click()
 const divider=page.getByRole('separator',{name:'调整引用列表与图谱宽度'})
 const bounds=(await divider.boundingBox())!
 await page.mouse.move(bounds.x,bounds.y+bounds.height/2);await page.mouse.down();await page.mouse.move(bounds.x+140,bounds.y+bounds.height/2,{steps:12});await page.mouse.up()
 expect(Number(await divider.getAttribute('aria-valuenow'))).toBeGreaterThan(55)
 await divider.focus();await page.keyboard.press('Home');await expect(divider).toHaveAttribute('aria-valuenow','25')
 await page.keyboard.press('End');await expect(divider).toHaveAttribute('aria-valuenow','75')
 await divider.dblclick();await expect(divider).toHaveAttribute('aria-valuenow','50')
 const height=page.getByRole('separator',{name:'调整关联笔记高度'})
 await height.focus();await page.keyboard.press('ArrowUp');await expect(height).toHaveAttribute('aria-valuenow','224')
})
