test('centers minimize glyph and unifies ordinary settings names',async({page},info)=>{
 await page.goto('/')
 await expect(page.getByRole('button',{name:'最小化窗口'}).locator('path')).toHaveAttribute('d','M6 12h12')
 await page.getByRole('button',{name:'打开设置',exact:true}).click()
 const typography=async(selector:string)=>page.locator(selector).first().evaluate(el=>{const s=getComputedStyle(el);return {size:s.fontSize,weight:s.fontWeight}})
 const ordinary=await typography('#settings-section-appearance > label')
 expect(await typography('#settings-section-appearance .settings-view__check strong')).toEqual(ordinary)
 await page.getByRole('tab',{name:'系统',exact:true}).click()
 expect(await typography('#settings-section-system .settings-view__check > span')).toEqual(ordinary)
 expect(await typography('#settings-section-system .settings-view__check strong')).toEqual(ordinary)
 await page.screenshot({path:info.outputPath('settings-type.png')})
})
