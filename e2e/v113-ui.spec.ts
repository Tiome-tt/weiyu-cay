test('applies font size on Enter only to the selected text and reports the caret size', async ({ page }) => {
  await page.goto('/e2e/rich-heading-fixture.html')
  const paragraph = page.getByRole('textbox', { name: '文档正文' }).locator('p').first()
  await paragraph.click()
  await paragraph.evaluate((element) => {
    const text = element.firstChild!
    const range = document.createRange()
    range.setStart(text, 0)
    range.setEnd(text, 2)
    const selection = window.getSelection()!
    selection.removeAllRanges()
    selection.addRange(range)
    element.dispatchEvent(new Event('mouseup', { bubbles: true }))
  })
  const input = page.getByRole('textbox', { name: '字号', exact: true })
  await input.fill('18')
  expect(await input.evaluate(element => getComputedStyle(element).boxShadow)).toBe('none')
  await expect(paragraph.locator('span[style*="font-size"]')).toHaveCount(0)
  await input.press('Enter')
  await expect(paragraph.locator('span[style*="font-size"]')).toHaveText('上方')
  await expect(input).toHaveValue('18')
  await page.getByRole('textbox', { name: '文档正文' }).locator('p').last().click()
  await expect(input).toHaveValue('11')
})

